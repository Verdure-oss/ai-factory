func TestBuildGitHubPullRequest(t *testing.T) {
	task := mustChangeRequestTask(t, ProviderGitHub)
	req, err := BuildChangeRequest(task, ChangeRequestOptions{
		Token:   "token",
		APIBase: "https://api.github.test",
	})
	if err != nil {
		t.Fatalf("BuildChangeRequest() error = %v", err)
	}
	if req.URL != "https://api.github.test/repos/liyuerich/ai-factory/pulls" {
		t.Fatalf("url = %q", req.URL)
	}
	if req.Headers["Authorization"] != "Bearer token" {
		t.Fatalf("authorization = %q", req.Headers["Authorization"])
	}
	var payload map[string]string
	if err := json.Unmarshal(req.Body, &payload); err != nil {
		t.Fatalf("json.Unmarshal() error = %v", err)
	}
	if payload["head"] != "ai-factory/fix-docs" {
		t.Fatalf("head = %q", payload["head"])
	}
	if payload["base"] != "main" {
		t.Fatalf("base = %q", payload["base"])
	}
	if payload["title"] != "Fix docs" {
		t.Fatalf("title = %q", payload["title"])
	}
}

