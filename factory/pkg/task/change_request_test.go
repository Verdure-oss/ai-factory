func mustChangeRequestTask(t *testing.T, provider string) *FactoryTask {
	t.Helper()
	repository := "liyuerich/ai-factory"
	host := ""
	if provider == ProviderGitLab {
		repository = "platform/ai/ai-factory"
		host = "gitlab.example.com"
	}
	task, err := Parse([]byte(`
apiVersion: factory.ai.gke.io/v1alpha1
kind: FactoryTask
metadata:
  name: fix-docs
spec:
  source:
    provider: ` + provider + `
    host: ` + host + `
    repository: ` + repository + `
    baseRef: main
  agent:
    name: builder
  sandbox:
    templateRef: go-dev
  work:
    commands:
    - go test ./...
  changeRequest:
    enabled: true
    branchPrefix: ai-factory
    commitMessage: Fix docs
    title: Fix docs
    body: Generated by ai-factory.
`))
	if err != nil {
		t.Fatalf("Parse() error = %v", err)
	}
	return task
}
