// ChangeRequestOptions configures provider API calls for PR/MR creation.
type ChangeRequestOptions struct {
	Token      string
	HTTPClient *http.Client
	APIBase    string
}

// ChangeRequest describes the provider API request needed to create a PR or MR.
type ChangeRequest struct {
	Provider string
	Method   string
	URL      string
	Headers  map[string]string
	Body     []byte
}

// ChangeRequestResult is the provider-neutral result of a PR/MR creation call.
type ChangeRequestResult struct {
	Provider      string
	URL           string
	AlreadyExists bool
}

// ChangeRequestError classifies provider API failures so controllers can
// distinguish setup problems from idempotent existing PRs/MRs.
type ChangeRequestError struct {
	Provider   string
	StatusCode int
	Status     string
	Reason     string
	Body       string
}

func (e *ChangeRequestError) Error() string {
	if e == nil {
		return ""
	}
	message := changeRequestErrorMessage(e.Body)
	if e.Reason != "" {
		if message != "" {
			return fmt.Sprintf("post %s change request: %s: %s: %s", e.Provider, e.Status, e.Reason, message)
		}
		return fmt.Sprintf("post %s change request: %s: %s", e.Provider, e.Status, e.Reason)
	}
	if message != "" {
		return fmt.Sprintf("post %s change request: unexpected status %s: %s", e.Provider, e.Status, message)
	}
	return fmt.Sprintf("post %s change request: unexpected status %s", e.Provider, e.Status)
}

// BuildChangeRequest builds a GitHub pull request or GitLab merge request call from a FactoryTask.
func BuildChangeRequest(task *FactoryTask, opts ChangeRequestOptions) (*ChangeRequest, error) {
	if task == nil {
		return nil, errors.New("FactoryTask is required")
	}
	if err := task.Validate(); err != nil {
		return nil, err
	}
	if !task.Spec.ChangeRequest.Enabled {
		return nil, errors.New("spec.changeRequest.enabled must be true")
	}
	changeBranch, targetBranch, _, _, _, _, _, _ := changeRequestDefaults(task)
	title := task.Spec.ChangeRequest.Title
	if title == "" {
		title = task.Spec.ChangeRequest.CommitMessage
	}
	if title == "" {
		title = fmt.Sprintf("Apply FactoryTask %s", task.Metadata.Name)
	}
	body := task.Spec.ChangeRequest.Body
	if body == "" {
		body = fmt.Sprintf("Generated by ai-factory for FactoryTask `%s`.", task.Metadata.Name)
	}

	switch task.Spec.Source.Provider {
	case ProviderGitHub:
		return buildGitHubPullRequest(task, opts, changeBranch, targetBranch, title, body)
	case ProviderGitLab:
		return buildGitLabMergeRequest(task, opts, changeBranch, targetBranch, title, body)
	default:
		return nil, fmt.Errorf("unsupported change request provider %q", task.Spec.Source.Provider)
	}
}

// CreateChangeRequest creates a GitHub pull request or GitLab merge request.
func CreateChangeRequest(ctx context.Context, task *FactoryTask, opts ChangeRequestOptions) (*ChangeRequestResult, error) {
	req, err := BuildChangeRequest(task, opts)
	if err != nil {
		return nil, err
	}
	client := opts.HTTPClient
	if client == nil {
		client = &http.Client{Timeout: 30 * time.Second}
	}
	if result, err := findExistingChangeRequest(ctx, task, opts, req, client); err != nil {
		return nil, err
	} else if result != nil {
		return result, nil
	}
	httpReq, err := http.NewRequestWithContext(ctx, req.Method, req.URL, bytes.NewReader(req.Body))
	if err != nil {
		return nil, fmt.Errorf("create change request: %w", err)
	}
	for key, value := range req.Headers {
		httpReq.Header.Set(key, value)
	}
	resp, err := client.Do(httpReq)
	if err != nil {
		return nil, fmt.Errorf("post %s change request: %w", req.Provider, err)
	}
	defer resp.Body.Close()
	if resp.StatusCode < 200 || resp.StatusCode >= 300 {
		body, _ := io.ReadAll(io.LimitReader(resp.Body, 1<<20))
		apiErr := classifyChangeRequestError(req.Provider, resp.StatusCode, resp.Status, string(body))
		if IsChangeRequestAlreadyExists(apiErr) {
			return &ChangeRequestResult{Provider: req.Provider, AlreadyExists: true}, nil
		}
		return nil, apiErr
	}
	resultURL, err := decodeChangeRequestURL(req.Provider, resp)
	if err != nil {
		return nil, err
	}
	return &ChangeRequestResult{Provider: req.Provider, URL: resultURL}, nil
}

func findExistingChangeRequest(ctx context.Context, task *FactoryTask, opts ChangeRequestOptions, createReq *ChangeRequest, client *http.Client) (*ChangeRequestResult, error) {
	changeBranch, _, _, _, _, _, _, _ := changeRequestDefaults(task)
	var lookupURL string
	switch task.Spec.Source.Provider {
	case ProviderGitHub:
		apiBase := strings.TrimRight(opts.APIBase, "/")
		if apiBase == "" {
			apiBase = defaultGitHubAPIBase
		}
		owner, repo, err := splitRepository(task.Spec.Source.Repository)
		if err != nil {
			return nil, err
		}
		values := url.Values{}
		values.Set("state", "open")
		values.Set("head", owner+":"+changeBranch)
		lookupURL = fmt.Sprintf("%s/repos/%s/%s/pulls?%s", apiBase, url.PathEscape(owner), url.PathEscape(repo), values.Encode())
	case ProviderGitLab:
		apiBase := strings.TrimRight(opts.APIBase, "/")
		if apiBase == "" {
			host := task.Spec.Source.Host
			if host == "" {
				host = "gitlab.com"
			}
			apiBase = fmt.Sprintf("https://%s/api/v4", host)
		}
		values := url.Values{}
		values.Set("state", "opened")
		values.Set("source_branch", changeBranch)
		lookupURL = fmt.Sprintf("%s/projects/%s/merge_requests?%s", apiBase, url.PathEscape(task.Spec.Source.Repository), values.Encode())
	default:
		return nil, nil
	}

	httpReq, err := http.NewRequestWithContext(ctx, http.MethodGet, lookupURL, nil)
	if err != nil {
		return nil, fmt.Errorf("create %s change request lookup: %w", createReq.Provider, err)
	}
	for key, value := range createReq.Headers {
		if strings.EqualFold(key, "Content-Type") {
			continue
		}
		httpReq.Header.Set(key, value)
	}
	resp, err := client.Do(httpReq)
	if err != nil {
		return nil, fmt.Errorf("lookup %s change request: %w", createReq.Provider, err)
	}
	defer resp.Body.Close()
	if resp.StatusCode < 200 || resp.StatusCode >= 300 {
		body, _ := io.ReadAll(io.LimitReader(resp.Body, 1<<20))
		return nil, classifyChangeRequestError(createReq.Provider, resp.StatusCode, resp.Status, string(body))
	}
	resultURL, err := decodeExistingChangeRequestURL(createReq.Provider, resp)
	if err != nil {
		return nil, err
	}
	if resultURL == "" {
		return nil, nil
	}
	return &ChangeRequestResult{Provider: createReq.Provider, URL: resultURL, AlreadyExists: true}, nil
}

func IsChangeRequestAlreadyExists(err error) bool {
	var apiErr *ChangeRequestError
	return errors.As(err, &apiErr) && apiErr.Reason == "already_exists"
}

func IsChangeRequestAuthError(err error) bool {
	var apiErr *ChangeRequestError
	return errors.As(err, &apiErr) && apiErr.Reason == "auth_failed"
}

func IsChangeRequestMissingBranch(err error) bool {
	var apiErr *ChangeRequestError
	return errors.As(err, &apiErr) && apiErr.Reason == "source_branch_missing"
}

func classifyChangeRequestError(provider string, statusCode int, status, body string) error {
	reason := ""
	lowerBody := strings.ToLower(body)
	switch {
	case statusCode == http.StatusUnauthorized || statusCode == http.StatusForbidden:
		reason = "auth_failed"
	case provider == ProviderGitHub && statusCode == http.StatusUnprocessableEntity && strings.Contains(lowerBody, "pull request already exists"):
		reason = "already_exists"
	case provider == ProviderGitLab && statusCode == http.StatusConflict && strings.Contains(lowerBody, "merge request already exists"):
		reason = "already_exists"
	case provider == ProviderGitLab && statusCode == http.StatusBadRequest && strings.Contains(lowerBody, "source branch"):
		reason = "source_branch_missing"
	case provider == ProviderGitHub && statusCode == http.StatusUnprocessableEntity && strings.Contains(lowerBody, "head"):
		reason = "source_branch_missing"
	}
	return &ChangeRequestError{
		Provider:   provider,
		StatusCode: statusCode,
		Status:     status,
		Reason:     reason,
		Body:       body,
	}
}

func buildGitHubPullRequest(task *FactoryTask, opts ChangeRequestOptions, head, base, title, body string) (*ChangeRequest, error) {
	token := changeRequestToken(task, opts, "GITHUB_TOKEN")
	if token == "" {
		return nil, errors.New(changeRequestTokenRequiredMessage(task, "GITHUB_TOKEN", "GitHub pull requests"))
	}
	apiBase := strings.TrimRight(opts.APIBase, "/")
	if apiBase == "" {
		apiBase = defaultGitHubAPIBase
	}
	payload, err := json.Marshal(map[string]string{
		"title": title,
		"body":  body,
		"head":  head,
		"base":  base,
	})
	if err != nil {
		return nil, fmt.Errorf("encode GitHub pull request: %w", err)
	}
	owner, repo, err := splitRepository(task.Spec.Source.Repository)
	if err != nil {
		return nil, err
	}
	return &ChangeRequest{
		Provider: ProviderGitHub,
		Method:   http.MethodPost,
		URL:      fmt.Sprintf("%s/repos/%s/%s/pulls", apiBase, url.PathEscape(owner), url.PathEscape(repo)),
		Headers: map[string]string{
			"Accept":        "application/vnd.github+json",
			"Authorization": "Bearer " + token,
			"Content-Type":  "application/json",
		},
		Body: payload,
	}, nil
}

func buildGitLabMergeRequest(task *FactoryTask, opts ChangeRequestOptions, sourceBranch, targetBranch, title, body string) (*ChangeRequest, error) {
	token := changeRequestToken(task, opts, "GITLAB_TOKEN")
	if token == "" {
		return nil, errors.New(changeRequestTokenRequiredMessage(task, "GITLAB_TOKEN", "GitLab merge requests"))
	}
	apiBase := strings.TrimRight(opts.APIBase, "/")
	if apiBase == "" {
		host := task.Spec.Source.Host
		if host == "" {
			host = "gitlab.com"
		}
		apiBase = fmt.Sprintf("https://%s/api/v4", host)
	}
	payload, err := json.Marshal(map[string]string{
		"title":         title,
		"description":   body,
		"source_branch": sourceBranch,
		"target_branch": targetBranch,
	})
	if err != nil {
		return nil, fmt.Errorf("encode GitLab merge request: %w", err)
	}
	return &ChangeRequest{
		Provider: ProviderGitLab,
		Method:   http.MethodPost,
		URL:      fmt.Sprintf("%s/projects/%s/merge_requests", apiBase, url.PathEscape(task.Spec.Source.Repository)),
		Headers: map[string]string{
			"Content-Type":  "application/json",
			"PRIVATE-TOKEN": token,
		},
		Body: payload,
	}, nil
}

func changeRequestToken(task *FactoryTask, opts ChangeRequestOptions, defaultEnv string) string {
	if opts.Token != "" {
		return opts.Token
	}
	if envName := strings.TrimSpace(task.Spec.ChangeRequest.AuthTokenEnv); envName != "" {
		if token := ReadConfig(envName); token != "" {
			return token
		}
	}
	return ReadConfig(defaultEnv)
}

func changeRequestTokenRequiredMessage(task *FactoryTask, defaultEnv, target string) string {
	if envName := strings.TrimSpace(task.Spec.ChangeRequest.AuthTokenEnv); envName != "" {
		return fmt.Sprintf("%s or %s is required to create %s", envName, defaultEnv, target)
	}
	return fmt.Sprintf("%s is required to create %s", defaultEnv, target)
}

func changeRequestErrorMessage(body string) string {
	var payload map[string]any
	if err := json.Unmarshal([]byte(body), &payload); err != nil {
		return ""
	}
	message, _ := payload["message"].(string)
	if len(message) > 300 {
		return message[:300]
	}
	return message
}

func decodeChangeRequestURL(provider string, resp *http.Response) (string, error) {
	var payload map[string]any
	if err := json.NewDecoder(resp.Body).Decode(&payload); err != nil {
		return "", fmt.Errorf("decode %s change request response: %w", provider, err)
	}
	for _, key := range []string{"html_url", "web_url"} {
		if value, ok := payload[key].(string); ok && value != "" {
			return value, nil
		}
	}
	return "", fmt.Errorf("%s change request response missing URL", provider)
}

func decodeExistingChangeRequestURL(provider string, resp *http.Response) (string, error) {
	var payload []map[string]any
	if err := json.NewDecoder(resp.Body).Decode(&payload); err != nil {
		return "", fmt.Errorf("decode existing %s change request response: %w", provider, err)
	}
	if len(payload) == 0 {
		return "", nil
	}
	for _, key := range []string{"html_url", "web_url"} {
		if value, ok := payload[0][key].(string); ok && value != "" {
			return value, nil
		}
	}
	return "", fmt.Errorf("existing %s change request response missing URL", provider)
}

func splitRepository(repository string) (string, string, error) {
	parts := strings.Split(repository, "/")
	if len(parts) != 2 || parts[0] == "" || parts[1] == "" {
		return "", "", fmt.Errorf("GitHub repository must look like owner/repo, got %q", repository)
	}
	return parts[0], parts[1], nil
}
